package fr.ftnl.texto.processor

import com.google.devtools.ksp.getAllSuperTypes
import com.google.devtools.ksp.processing.*
import com.google.devtools.ksp.symbol.*
import com.google.devtools.ksp.validate
import java.io.OutputStreamWriter

class TableProcessor(
    private val codeGenerator: CodeGenerator,
    private val logger: KSPLogger
) : SymbolProcessor {
    private val foundTables = mutableSetOf<KSClassDeclaration>()
    
    override fun process(resolver: Resolver): List<KSAnnotated> {
        val baseTableName = "fr.ftnl.texto.database.types.BaseIntIdTable"
        val symbols = resolver.getAllFiles()
            .flatMap { it.declarations }
            .filterIsInstance<KSClassDeclaration>()
            .filter { it.classKind == ClassKind.OBJECT }
            .filter { classDeclaration ->
                classDeclaration.getAllSuperTypes().any { superType ->
                    superType.declaration.qualifiedName?.asString() == baseTableName
                }
            }
            .toList()
        foundTables.addAll(symbols)
        return symbols.filterNot { it.validate() }
    }
    
    override fun finish() {
        if (foundTables.isEmpty()) {
            return // Aucune table trouvée, on ne fait rien.
        }
        
        val tableNames = foundTables.map { it.qualifiedName!!.asString() }
        val sourceFiles = foundTables.mapNotNull { it.containingFile }.toTypedArray()
        
        val packageName = "fr.ftnl.texto.database"
        val fileName = "DatabaseRegistry"
        val fileContent = """
package $packageName

import fr.ftnl.texto.database.types.BaseIntIdTable
${tableNames.joinToString(separator = "\n") { "import $it" }}

/**
 * THIS FILE IS GENERATED BY KSP. DO NOT EDIT.
 * Registre central de toutes les tables de la base de données.
 */
object $fileName {
    val tables: Array<BaseIntIdTable> = arrayOf(
        ${tableNames.joinToString(separator = ",\n        ") { it.substringAfterLast('.') }}
    )
}
        """.trimIndent()
        val file = codeGenerator.createNewFile(
            dependencies = Dependencies(true, *sourceFiles),
            packageName = packageName,
            fileName = fileName
        )
        OutputStreamWriter(file, "UTF-8").use { it.write(fileContent) }
    }
}

class TableProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor {
        return TableProcessor(environment.codeGenerator, environment.logger)
    }
}